// Regenerates TS types and Pydantic models from schemas/*.json, the single source of truth.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileFromFile } from 'json-schema-to-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = join(root, 'schemas');
const tsOut = join(root, 'src/generated');
const botDir = resolve(root, '../../services/bot');
const pyOut = join(botDir, 'app/contracts/generated');
const BANNER =
  'Generated by packages/contracts/scripts/generate.mjs. Do not edit; edit the schema and run `make contracts`.';

const schemas = readdirSync(schemaDir)
  .filter((file) => file.endsWith('.json'))
  .sort();

function resetDir(dir) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
}

async function generateTypeScript() {
  resetDir(tsOut);
  const modules = [];
  for (const file of schemas) {
    const name = basename(file, '.json');
    const ts = await compileFromFile(join(schemaDir, file), { cwd: schemaDir, bannerComment: `// ${BANNER}` });
    writeFileSync(join(tsOut, `${name}.ts`), ts);
    modules.push(name);
  }
  const index = modules.map((name) => `export * from './${name}.js';`).join('\n');
  writeFileSync(join(tsOut, 'index.ts'), `// ${BANNER}\n${index || 'export {};'}\n`);
}

function generatePython() {
  resetDir(pyOut);
  writeFileSync(join(pyOut, '__init__.py'), `# ${BANNER}\n`);
  if (schemas.length === 0) return;
  execFileSync(
    'uv',
    [
      'run',
      '--project',
      botDir,
      'datamodel-codegen',
      '--input',
      schemaDir,
      '--input-file-type',
      'jsonschema',
      '--output',
      pyOut,
      '--output-model-type',
      'pydantic_v2.BaseModel',
      '--custom-file-header',
      `# ${BANNER}`,
      '--disable-timestamp',
    ],
    { stdio: 'inherit' },
  );
}

await generateTypeScript();
generatePython();
console.log(`contracts: generated ${schemas.length} schema(s)`);
